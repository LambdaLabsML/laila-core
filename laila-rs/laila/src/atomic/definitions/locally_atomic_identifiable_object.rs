/// The identity surface `laila.atomic` needs from
/// `basics.definitions.identifiable_object._LAILA_IDENTIFIABLE_OBJECT`
/// (`obj.global_id` / `obj.uuid` on mixin implementors).
///
/// Typed laila objects implement it from their [`Identity`] (`Entry`), a
/// pydantic model instance from its `_uuid` / `_scopes` / `_evolution`
/// private attributes ([`ModelInstance`]), and a `py_class!` subclass of
/// an identifiable mixin -- `class C(_LAILA_LOCALLY_ATOMIC_IDENTIFIABLE_OBJECT)`
/// -- from the same private attributes in its `__dict__`
/// ([`dict_identity`], installed by the [`dict_identity!`](crate::dict_identity)
/// macro that `laila::python!` emits next to `impl Mixin for C {}`).
pub trait HasIdentity {
    /// `obj.global_id` -- `LAILA:<scopes>:<uuid>[@evolution=<n>]`.
    fn global_id(&self) -> String;
    /// `obj.uuid`
    fn uuid(&self) -> String;
}

/// The identity of a dynamic object (`py_class!` / any `__dict__`) that
/// derives from `_LAILA_IDENTIFIABLE_OBJECT` without constructor
/// arguments: `_uuid` is a uuid4 minted on first use, `_scopes` the base
/// class's `["OBJECT"]`, `_evolution` `None` -- exactly what
/// `_LAILA_IDENTIFIABLE_OBJECT.__init__()` stores in
/// `__pydantic_private__`. Explicit `_uuid` / `_scopes` / `_evolution`
/// entries in the `__dict__` win.
pub fn dict_identity(attrs: &PyAttrs) -> Identity {
    let uuid = attrs
        .__setdefault__("_uuid", || Arg::Str(crate::_compat::uuid::uuid4().into()))
        .__str__();
    let scopes: Vec<String> = match attrs.get("_scopes") {
        Some(s) if !s.is_none() => s
            .__iter__()
            .map(|v| v.iter().map(|x| x.__str__()).collect())
            .unwrap_or_default(),
        _ => alloc::vec![crate::macros::strings::_OBJECT_SCOPE.into()],
    };
    let evolution = attrs.get("_evolution").and_then(|e| e.as_i64());
    let creation_timestamp = attrs
        .get("_creation_timestamp")
        .filter(|t| !t.is_none())
        .map(|t| t.__str__());
    Identity {
        uuid,
        scopes,
        evolution,
        nickname: None,
        creation_timestamp,
    }
}

/// `impl HasIdentity for C` for a `py_class!` (any [`HasAttrs`]) that
/// inherits `_LAILA_IDENTIFIABLE_OBJECT` through an atomic mixin: the
/// identity lives in the instance `__dict__` ([`dict_identity`]).
#[macro_export]
macro_rules! dict_identity {
    ($t:ty) => {
        impl $crate::atomic::definitions::HasIdentity for $t {
            fn global_id(&self) -> $crate::python::__rt::String {
                $crate::atomic::definitions::dict_identity($crate::python::HasAttrs::__attrs__(
                    self,
                ))
                .global_id()
            }
            fn uuid(&self) -> $crate::python::__rt::String {
                $crate::atomic::definitions::dict_identity($crate::python::HasAttrs::__attrs__(
                    self,
                ))
                .uuid
            }
        }
    };
}

impl HasIdentity for ModelInstance {
    fn global_id(&self) -> String {
        match PyObject::__getattr__(self, "global_id") {
            Ok(g) => g.__str__(),
            Err(_) => identity_of(self).global_id(),
        }
    }
    fn uuid(&self) -> String {
        identity_of(self).uuid
    }
}

// ---------------------------------------------------------------------------
// The mixin as a pydantic base class
// ---------------------------------------------------------------------------
// `class Pool(_LAILA_CLI_CAPABLE_CLASS, _LAILA_LOCALLY_ATOMIC_IDENTIFIABLE_OBJECT)`
// needs the mixin as a `ModelClass` base: its MRO contributes the identity
// hooks of `_LAILA_IDENTIFIABLE_OBJECT` and the per-instance lock. A model
// instance keeps the lock under `_local_lock` in `__pydantic_private__`,
// exactly where Python's `object.__setattr__(self, "_local_lock", RLock())`
// puts it.

/// The per-instance re-entrant lock of a model instance (created on first use).
pub fn model_local_lock(inst: &ModelInstance) -> RLock {
    if let Some(l) = inst
        .private(super::locally_atomic_object::LOCAL_LOCK_ATTR)
        .and_then(|a| a.downcast_ref::<RLock>().cloned())
    {
        return l;
    }
    let l = RLock::new();
    inst.set_private(
        super::locally_atomic_object::LOCAL_LOCK_ATTR,
        crate::python::IntoArg::into_arg(l.clone()),
    );
    l
}

struct MixinHooks;

impl crate::_compat::pydantic::ModelHooks for MixinHooks {
    fn call_method(&self, inst: &ModelInstance, name: &str, args: Args) -> Option<Result<Arg>> {
        match name {
            "lock" => {
                let timeout = args.get("timeout_s");
                let timeout = args.positional.first().cloned().unwrap_or(timeout);
                Some(
                    super::locally_atomic_object::timeout_arg(&timeout)
                        .map(|t| Arg::Bool(model_local_lock(inst).acquire(t))),
                )
            }
            "unlock" => Some(model_local_lock(inst).release().map(|()| Arg::None)),
            "atomic" => Some(
                super::locally_atomic_object::DynAtomicContext::new(
                    model_local_lock(inst),
                    inst.class_name(),
                    args,
                )
                .map(crate::python::IntoArg::into_arg),
            ),
            "locked" => Some(Ok(Arg::Bool(model_local_lock(inst).locked()))),
            _ => None,
        }
    }
    fn method_names(&self) -> &'static [&'static str] {
        &["atomic", "lock", "unlock", "locked"]
    }
}

static MIXIN_HOOKS: MixinHooks = MixinHooks;

static MIXIN_CLASS: crate::_compat::pydantic::LazyClass =
    crate::_compat::pydantic::LazyClass::new(|| crate::_compat::pydantic::ModelClass {
        name: "_LAILA_LOCALLY_ATOMIC_IDENTIFIABLE_OBJECT",
        module: "laila.atomic.definitions.locally_atomic_identifiable_object",
        bases: alloc::vec![
            crate::basics::definitions::identifiable_object::_LAILA_IDENTIFIABLE_OBJECT::__class__(
            )
        ],
        fields: Vec::new(),
        private_attrs: Vec::new(),
        class_vars: Vec::new(),
        hooks: Some(&MIXIN_HOOKS),
    });

/// The mixin as a class descriptor (a base of the pydantic-style laila
/// classes: pools, the pool router, `MultiBuffer`).
pub fn mixin_class() -> &'static crate::_compat::pydantic::ModelClass {
    &MIXIN_CLASS
}

/// `_LAILA_LOCALLY_ATOMIC_IDENTIFIABLE_OBJECT(uuid=None, scopes=None, evolution=None, nickname=None)`:
