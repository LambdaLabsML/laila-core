/// Identifiable object with a per-instance reentrant lock.
///
/// Pure mixin: defines no extra fields or methods of its own. Inherits
/// identity machinery (uuid / scopes / evolution / global_id) from
/// `_LAILA_IDENTIFIABLE_OBJECT` and locking machinery (`lock` / `unlock` /
/// `atomic`) from `_LAILA_LOCALLY_ATOMIC_OBJECT`.
#[allow(non_camel_case_types)]
pub trait _LAILA_LOCALLY_ATOMIC_IDENTIFIABLE_OBJECT: HasAttrs + HasIdentity {
    crate::local_atomic_methods!();

    /// `with obj.atomic(*, scope="local", timeout_s=None) as locked:`
    #[pysig("atomic(self, *, scope=\"local\", timeout_s=None)")]
    fn atomic(&self, args: impl Into<Args>) -> Result<AtomicContext<Self>>
    where
        Self: Clone + Sized,
    {
        super::locally_atomic_object::atomic_context(
            self,
            scope,
            timeout_s,
            Arg::None,
            "_LAILA_LOCALLY_ATOMIC_OBJECT",
            false,
        )
    }
}

