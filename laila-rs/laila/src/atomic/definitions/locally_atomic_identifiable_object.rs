//! Identifiable + locally-atomic mixin.
//!
//! Single-purpose convenience module: glues `_LAILA_IDENTIFIABLE_OBJECT`
//! (identity, global ids, serialisation hooks) and
//! [`_LAILA_LOCALLY_ATOMIC_OBJECT`] (per-instance reentrant lock,
//! `with self.atomic(): ...`) into one base class so subclasses can pick up
//! both concerns by inheriting from a single name. This is the most-used
//! base class in laila -- pools, taskforces, comm protocols, futures and many
//! more inherit from it.
//!
//! Rust has no multiple inheritance, so the mixin is a trait with the same
//! provided methods as the local-lock base (generated by
//! [`local_atomic_methods!`]) plus the identity supertrait. A type implements
//! exactly one of the three mixin traits -- that keeps `obj.atomic()`
//! unambiguous.
//!
//! This file also hosts the Rust twin of `laila.utils.decorators.synchronized`
//! (the decorator that locks every identifiable-atomic argument of a call in
//! `id()` order), because it is the only consumer of the "is this object an
//! identifiable atomic object?" question.

