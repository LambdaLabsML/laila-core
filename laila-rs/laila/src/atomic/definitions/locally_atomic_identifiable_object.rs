// Python keeps this in `utils/decorators/synchronized.py`;
// `laila::utils::decorators::synchronized` re-exports it from here.

/// `isinstance(obj, _LAILA_LOCALLY_ATOMIC_IDENTIFIABLE_OBJECT)` on a dynamic
/// value: `(id(obj), its local lock)` when it is one, else `None`.
pub fn atomic_lock_of(a: &Arg) -> Option<(usize, RLock)> {
    match a {
        Arg::Object(o) => o
            .__atomic_lock__()
            .map(|l| (alloc::sync::Arc::as_ptr(o) as *const () as usize, l)),
        // `Entry` (and its `Manifest` subclass) carry the mixin's local lock.
        Arg::Entry(e) => Some((e.id(), ensure_local_lock(e.__attrs__()))),
        // Pools and futures become `_LAILA_LOCALLY_ATOMIC_IDENTIFIABLE_OBJECT`s
        // with their own rewrites (Phase 3).
        _ => None,
    }
}

/// Run `f` with every lock in `targets` held, acquired in `id()` order
/// (what keeps `@synchronized` deadlock-free) and released in reverse.
pub fn synchronized_call<R>(
    targets: &[(usize, RLock)],
    f: impl FnOnce() -> Result<R>,
) -> Result<R> {
    let mut sorted: Vec<&(usize, RLock)> = targets.iter().collect();
    sorted.sort_by_key(|(id, _)| *id);
    for (_, l) in &sorted {
        l.acquire(None);
    }
    let r = f();
    for (_, l) in sorted.iter().rev() {
        let _ = l.release();
    }
    r
}

/// `@synchronized` for typed Rust code: lock `targets` (any mix of mixin
/// implementors) in `id()` order around `f`.
pub fn synchronized_on<R>(
    targets: &[&dyn LocalLockHandle],
    f: impl FnOnce() -> Result<R>,
) -> Result<R> {
    let handles: Vec<(usize, RLock)> = targets.iter().map(|t| t.__local_lock_handle__()).collect();
    synchronized_call(&handles, f)
}

/// Object-safe access to `(id(obj), local lock)` for [`synchronized_on`].
pub trait LocalLockHandle {
    fn __local_lock_handle__(&self) -> (usize, RLock);
}

impl<T: HasAttrs> LocalLockHandle for T {
    fn __local_lock_handle__(&self) -> (usize, RLock) {
        (
            attrs_id(self.__attrs__()),
            ensure_local_lock(self.__attrs__()),
        )
    }
}

/// `isinstance(x, _LAILA_LOCALLY_ATOMIC_IDENTIFIABLE_OBJECT)` for dynamic values.
pub fn is_locally_atomic_identifiable(x: &Arg) -> bool {
    atomic_lock_of(x).is_some()
}
